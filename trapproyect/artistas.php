        <!-- 2. Gucci Mane -->
        <div class="accordion-item">
            <h2 class="accordion-header">
                <button class="accordion-button collapsed" type="button" data-bs-toggle="collapse" data-bs-target="#artista2">
                    2. Gucci Mane
                </button>
            </h2>
            <div id="artista2" class="accordion-collapse collapse" data-bs-parent="#accordionArtistas">
                <div class="accordion-body">
                    <div class="row">
                        <div class="col-md-4">
                            <img src="img/gucci-mane.jpg" alt="Gucci Mane" class="img-fluid rounded shadow mb-3">
                            <p class="mb-1"><strong>Nombre real:</strong> Radric Delantic Davis</p>
                            <p class="mb-1"><strong>Origen:</strong> Bessemer, Alabama; se trasladó a Atlanta cuando era niño.</p>
                            <p class="mb-1"><strong>Escena:</strong> Trap de Atlanta.</p>
                            <p class="mb-1"><strong>Trabajos destacados:</strong> <em>Trap House</em> (2005), "Icy", <em>The State vs. Radric Davis</em>, <em>Everybody Looking</em>.</p>
                            <p class="mb-3"><strong>Sello:</strong> Fundador de 1017.</p>
                        </div>
                        <div class="col-md-8">
                            <h5>¿De dónde salió?</h5>
                            <p>
                                Gucci Mane nació en Bessemer, Alabama, y se mudó a Atlanta durante su infancia.
                                Desde joven escribió poesía y rimas. Su carrera comenzó a crecer en la escena
                                local con "Black Tee", y en 2005 publicó su álbum debut <em>Trap House</em>.
                                Ese disco y el sencillo "Icy" ayudaron a convertirlo en una figura conocida
                                fuera de Atlanta.
                            </p>
                            <h5>¿Cómo triunfó?</h5>
                            <p>
                                Su éxito no dependió únicamente de álbumes comerciales. Gucci construyó gran
                                parte de su reputación mediante una cantidad enorme de mixtapes, colaboraciones
                                y apariciones junto a otros raperos. Además, su trabajo con productores como
                                Zaytoven ayudó a desarrollar una estética que se volvería fundamental para el
                                trap de Atlanta.
                            </p>
                            <h5>Influencia en el trap</h5>
                            <p>
                                Gucci Mane es considerado uno de los grandes pioneros del trap junto con T.I.
                                y Jeezy. Su influencia no se limita a su propia música: también funcionó como
                                mentor, colaborador y descubridor de nuevos talentos, como Waka Flocka Flame,
                                Young Thug y otros nombres del rap sureño.
                            </p>
                            <h5>Mensaje y temas recurrentes</h5>
                            <p>
                                La primera etapa de Gucci se concentra fuertemente en experiencias de calle,
                                drogas, dinero, supervivencia, lujo y las consecuencias de ese estilo de vida.
                                Sin embargo, después de su paso por prisión también comenzó a hablar
                                públicamente de cambio personal, disciplina y reinvención.
                            </p>
                            <div class="bg-light p-3 rounded">
                                <strong>Importancia resumida:</strong> Gucci Mane no solo ayudó a definir cómo
                                sonaba el trap: también ayudó a crear el ecosistema de artistas, productores,
                                mixtapes y sellos que permitió que Atlanta se transformara en uno de los
                                centros del rap mundial.
                            </div>
                        </div>
                    </div>
                </div>
            </div>
