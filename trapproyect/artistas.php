                    4. Chief Keef
                </button>
            </h2>
            <div id="artista4" class="accordion-collapse collapse" data-bs-parent="#accordionArtistas">
                <div class="accordion-body">
                    <div class="row">
                        <div class="col-md-4">
                            <img src="img/chiefkeef.jpg" alt="Chief Keef" class="img-fluid rounded shadow mb-3">
                            <p class="mb-1"><strong>Nombre real:</strong> Keith Cozart</p>
                            <p class="mb-1"><strong>Origen:</strong> South Side de Chicago, Illinois.</p>
                            <p class="mb-1"><strong>Escena principal:</strong> Drill de Chicago.</p>
                            <p class="mb-3"><strong>Trabajos destacados:</strong> "I Don't Like", "Love Sosa", <em>Finally Rich</em>, "Faneto".</p>
                        </div>
                        <div class="col-md-8">
                            <h5>¿De dónde salió?</h5>
                            <p>
                                Chief Keef comenzó a rapear siendo adolescente en el South Side de Chicago.
                                Sus primeras mixtapes y videos circularon localmente y por internet. Mientras
                                se encontraba bajo arresto domiciliario, continuó publicando videos en YouTube,
                                lo que contribuyó a aumentar rápidamente su popularidad entre los jóvenes de
                                Chicago.
                            </p>
                            <h5>¿Cómo triunfó?</h5>
                            <p>
                                Su gran momento llegó con "I Don't Like" en 2012. La canción se convirtió en
                                un éxito local, recibió un remix de Kanye West y llamó la atención de grandes
                                sellos. Chief Keef terminó firmando con Interscope y lanzó su álbum
                                <em>Finally Rich</em> a finales de 2012.
                            </p>
                            <h5>Influencia en el trap</h5>
                            <p>
                                Es importante aclarar que Chief Keef pertenece principalmente al drill, no al
                                trap de Atlanta. Sin embargo, su influencia sobre el rap de los años 2010 y
                                sobre las generaciones posteriores de trap es enorme: el uso de internet y
                                videos de bajo presupuesto para construir una carrera, flows simples y
                                repetitivos, ad-libs, letras directas y una actitud extremadamente cruda.
                            </p>
                            <h5>Mensaje y temas recurrentes</h5>
                            <p>
                                Gran parte de su música temprana funciona como una representación directa de
                                la violencia, los conflictos, las pandillas y la vida juvenil del South Side
                                de Chicago. Su figura también representa independencia creativa y la
                                posibilidad de triunfar usando internet y una estética propia.
                            </p>
                            <div class="bg-light p-3 rounded">
                                <strong>Importancia resumida:</strong> Chief Keef cambió la manera en que una
                                generación entendió el rap callejero. Aunque su género principal es el drill,
                                su influencia llegó al trap, al rap de SoundCloud y a numerosas escenas
                                posteriores de Estados Unidos y otros países.
                            </div>
                        </div>
                    </div>
                </div>
            </div>
