                            <p class="mb-1"><strong>Origen:</strong> Walterboro, Carolina del Sur; se trasladó a Atlanta durante su infancia.</p>
                            <p class="mb-1"><strong>Zona asociada:</strong> Kirkwood, Atlanta.</p>
                            <p class="mb-1"><strong>Escena:</strong> Trap / street rap de Atlanta.</p>
                            <p class="mb-1"><strong>Trabajos destacados:</strong> <em>Street Lottery</em>, "Colombia", "Jugg King".</p>
                            <p class="mb-3"><strong>Colectivo:</strong> Black Migo Gang.</p>
                        </div>
                        <div class="col-md-8">
                            <h5>¿De dónde salió?</h5>
                            <p>
                                Young Scooter nació en Carolina del Sur y se trasladó a Atlanta cuando era
                                niño. Creció en el sector de Kirkwood y tuvo una relación de amistad desde
                                joven con Future. Después de problemas relacionados con el tráfico de drogas
                                decidió concentrarse seriamente en la música.
                            </p>
                            <h5>¿Cómo triunfó?</h5>
                            <p>
                                Sus primeras grabaciones no tuvieron un gran impacto, pero comenzó a ganar
                                reconocimiento con mixtapes como <em>Finessin and Flexin</em>. Su gran salto
                                llegó en 2013 con <em>Street Lottery</em> y especialmente con la canción
                                "Colombia". Las colaboraciones con Future, Gucci Mane, Waka Flocka Flame y
                                otros artistas de Atlanta también ayudaron a posicionarlo dentro del circuito
                                del trap.
                            </p>
                            <h5>Influencia en el trap</h5>
                            <p>
                                Young Scooter representa muy bien la segunda generación de rap callejero de
                                Atlanta construida alrededor de mixtapes, colaboraciones y redes locales. Él
                                mismo ha llamado a su estilo "count music", una idea asociada a contar dinero,
                                trabajar, moverse y mantenerse enfocado en producir recursos.
                            </p>
                            <h5>Mensaje y temas recurrentes</h5>
                            <p>
                                Scooter ha explicado que rapea sobre su vida, lo que ha vivido, lo que ocurre
                                en las calles y la lucha diaria. Sus temas se enfocan en el dinero, la
                                perseverancia, el hustle, la familia, las consecuencias de la vida callejera y
                                la necesidad de seguir trabajando.
                            </p>
                            <div class="bg-light p-3 rounded">
                                <strong>Importancia resumida:</strong> Young Scooter representa el lado más
                                callejero y menos comercial del trap de Atlanta: una música construida desde
                                las mixtapes, el hustle y la experiencia directa de la calle.
                            </div>
                        </div>
                    </div>
                </div>
