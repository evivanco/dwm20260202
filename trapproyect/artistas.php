                            <p class="mb-1"><strong>Escena:</strong> Rap callejero de Filadelfia / hip-hop con fuerte uso de producción trap.</p>
                            <p class="mb-1"><strong>Trabajos destacados:</strong> <em>Dreamchasers</em>, "Ima Boss", <em>Dreams and Nightmares</em>, <em>Championships</em>.</p>
                            <p class="mb-3"><strong>Sello/proyecto:</strong> Dream Chasers.</p>
                        </div>
                        <div class="col-md-8">
                            <h5>¿De dónde salió?</h5>
                            <p>
                                Meek Mill creció en Filadelfia y comenzó como rapero de batalla. Antes de su
                                éxito nacional desarrolló su reputación en las calles, mediante freestyles,
                                batallas y mixtapes. Esa cultura competitiva de Filadelfia explica parte de su
                                estilo: voz intensa, interpretación agresiva y letras centradas en demostrar
                                hambre y ambición.
                            </p>
                            <h5>¿Cómo triunfó?</h5>
                            <p>
                                Después de años desarrollando reconocimiento local, Meek se vinculó con
                                figuras importantes del rap. En 2011 firmó con Maybach Music Group, el sello
                                de Rick Ross, y obtuvo mayor exposición gracias a canciones como "Tupac Back"
                                e "Ima Boss". Más adelante, <em>Championships</em> (2018) debutó en el número
                                uno del Billboard 200.
                            </p>
                            <h5>Influencia en el mundo del trap</h5>
                            <p>
                                Meek Mill no es un artista de trap puro ni uno de los fundadores del género.
                                Su base está en el street rap de la Costa Este. Sin embargo, durante su
                                carrera ha trabajado ampliamente sobre instrumentales y técnicas de producción
                                asociadas al trap y ayudó a adaptar ese sonido a un estilo de rap más lírico,
                                agresivo y motivacional.
                            </p>
                            <h5>Mensaje y temas recurrentes</h5>
                            <p>
                                El concepto más importante de Meek Mill es "Dream Chasers": perseguir los
                                sueños sin importar el punto de partida. Sus letras suelen hablar de pobreza,
                                hambre de éxito, dinero, pérdidas, traición, perseverancia y ascenso social.
                                Después de sus experiencias con prisión, también convirtió la reforma del
                                sistema de justicia penal en una parte importante de su mensaje público.
                            </p>
                            <div class="bg-light p-3 rounded">
                                <strong>Importancia resumida:</strong> Meek Mill aporta al mundo relacionado
                                con el trap una perspectiva de perseverancia y ambición. Su carrera muestra la
                                transición desde batallas y mixtapes callejeras hasta el éxito internacional, y
                                posteriormente hacia el activismo social.
                            </div>
                        </div>
