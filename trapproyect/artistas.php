    <h1 class="text-center mb-3">Artistas que Influenciaron el Trap</h1>
    <p class="lead text-center mb-5">
        El trap nació y se consolidó principalmente en el sur de Estados Unidos, especialmente en Atlanta,
        pero con el tiempo su sonido y su cultura se mezclaron con otras escenas del rap. Los cinco artistas
        de esta página no ocupan exactamente el mismo lugar dentro del género: algunos son figuras centrales
        del trap de Atlanta, mientras que otros provienen de escenas cercanas (como el drill de Chicago o el
        street rap de Filadelfia) cuya música terminó influyendo fuertemente en el trap moderno.
    </p>

