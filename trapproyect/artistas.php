        <div class="accordion-item">
            <h2 class="accordion-header">
                <button class="accordion-button" type="button" data-bs-toggle="collapse" data-bs-target="#artista1">
                    1. Waka Flocka Flame
                </button>
            </h2>
            <div id="artista1" class="accordion-collapse collapse show" data-bs-parent="#accordionArtistas">
                <div class="accordion-body">
                    <div class="row">
                        <div class="col-md-4">
                            <img src="img/waka-flocka.jpg" alt="Waka Flocka Flame" class="img-fluid rounded shadow mb-3">
                            <p class="mb-1"><strong>Nombre real:</strong> Juaquin James Malphurs</p>
                            <p class="mb-1"><strong>Origen:</strong> Nació en Queens, Nueva York, y se crió en Georgia, cerca de Atlanta.</p>
                            <p class="mb-1"><strong>Escena:</strong> Trap de Atlanta / Brick Squad.</p>
                            <p class="mb-3"><strong>Trabajos destacados:</strong> "O Let's Do It", "Hard in da Paint", "No Hands" y el álbum <em>Flockaveli</em> (2010).</p>
                        </div>
                        <div class="col-md-8">
                            <h5>¿De dónde salió?</h5>
                            <p>
                                Waka Flocka Flame nació en Nueva York, pero su identidad musical se formó en
                                Georgia. Se desarrolló dentro de la escena de Atlanta y estuvo estrechamente
                                vinculado a Gucci Mane y al colectivo Brick Squad. Gucci fue uno de sus primeros
                                apoyos importantes y ayudó a introducirlo en el circuito profesional.
                            </p>
                            <h5>¿Cómo triunfó?</h5>
                            <p>
                                Su primer gran impulso llegó con "O Let's Do It" en 2009. Después publicó
                                <em>Flockaveli</em> en 2010, disco que entró al Top 10 del Billboard 200 y
                                contenía temas como "Hard in da Paint" y "No Hands". La combinación de Waka
                                con productores como Lex Luger fue fundamental: bases agresivas, bombos 808
                                muy fuertes, hi-hats intensos, sintetizadores oscuros y coros diseñados para
                                generar energía.
                            </p>
                            <h5>Influencia en el trap</h5>
                            <p>
                                Waka ayudó a llevar el trap hacia una versión mucho más explosiva y orientada
                                a conciertos, clubes y grandes parlantes. Su estilo redujo la importancia de la
                                complejidad lírica y aumentó el protagonismo de la energía, los gritos, los
                                ad-libs y la producción. <em>Flockaveli</em> se convirtió en una referencia para
                                la generación de trap más agresivo de comienzos de los años 2010.
                            </p>
                            <h5>Mensaje y temas recurrentes</h5>
                            <p>
                                Su música suele girar alrededor de la vida callejera, la lealtad, la
                                confrontación, la resistencia y la celebración. Más que presentar una enseñanza
                                social directa, gran parte de su obra busca transmitir intensidad y representar
                                el ambiente del que surgió.
                            </p>
                            <div class="bg-light p-3 rounded">
                                <strong>Importancia resumida:</strong> Waka Flocka Flame fue una figura clave
                                para convertir el trap de finales de los 2000 en un sonido más agresivo, masivo
                                y preparado para dominar fiestas, estadios y clubes.
                            </div>
                        </div>
                    </div>
                </div>
            </div>
