        <div class="col-md-6 order-md-1">
            <h3>Expansión</h3>
            <p>
                A comienzos de los años 2000 el trap adquirió una identidad mucho más definida gracias
                principalmente a T.I., Jeezy y Gucci Mane, conocidos frecuentemente como la
                "Trinidad del Trap".
            </p>
            <p>
                T.I. publicó en 2003 el álbum <em>Trap Muzik</em>, considerado una obra fundamental para
                consolidar el nombre y la identidad del género. Antes de alcanzar el éxito, varios de
                estos artistas distribuían mixtapes de manera independiente en Atlanta, incluso
                vendiéndolas directamente desde automóviles. NPR señala precisamente a 2003 como un
                momento decisivo para el establecimiento del trap como un subgénero reconocible del rap.
            </p>
            <p>
                En la producción también surgieron figuras fundamentales como DJ Toomp y Shawty Redd. El
                sonido empezó a caracterizarse por bajos muy marcados, sintetizadores, hi-hats rápidos y
                el uso de patrones ternarios.
            </p>
            <p><strong>Artistas fundamentales:</strong> T.I., Jeezy y Gucci Mane.</p>
            <p><strong>Productores importantes:</strong> DJ Toomp y Shawty Redd.</p>
        </div>
    </div>

    <!-- Actualidad -->
    <div class="row align-items-center mb-5">
        <div class="col-md-6">
            <img src="img/chiefkeef.jpg" alt="El trap en la actualidad" class="img-fluid rounded shadow">
        </div>
        <div class="col-md-6">
            <h3>Actualidad</h3>
            <p>
                Durante la década de 2010, el trap pasó de ser una escena principalmente sureña a
                convertirse en uno de los sonidos dominantes del hip-hop estadounidense.
            </p>
            <p>
                El productor Lex Luger tuvo un papel importante en esta evolución, trabajando con
                artistas como Waka Flocka Flame y ayudando a popularizar una producción basada en
                grandes bajos y sonidos derivados de la caja de ritmos Roland TR-808. Posteriormente,
                artistas como Future, Migos,chief keef y Young Thug llevaron el género hacia audiencias mucho
                más amplias.
            </p>
            <p>
                El trap además comenzó a mezclarse con otros géneros. Sus técnicas de producción fueron
                utilizadas por artistas de hip-hop, pop y música electrónica, influyendo en músicos como
                Jay-Z, Kanye West, Beyoncé, Miley Cyrus y Taylor Swift, mientras que productores
                electrónicos como Rustie y Hudson Mohawke contribuyeron a introducir ese sonido en
                clubes y festivales.
            </p>
            <p>
                Por eso actualmente el trap ya no se limita a Atlanta: sus características musicales
                pueden encontrarse en el hip-hop, pop, EDM y distintas escenas urbanas alrededor del mundo.
            </p>
            <p><strong>Artistas representativos:</strong> Future, Migos, Young Thug, Waka Flocka Flame y 21 Savage.</p>
        </div>
