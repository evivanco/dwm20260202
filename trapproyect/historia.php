    <h1 class="text-center mb-3">Historia del Trap</h1>
    <p class="lead text-center mb-5">
        El trap es un subgénero del hip-hop que nació en el sur de Estados Unidos, especialmente en
        Atlanta, Georgia, a finales de los años 90 y comienzos de los 2000. Surgió dentro de comunidades
        afroamericanas marcadas por la segregación, la pobreza, el narcotráfico y la falta de oportunidades.
        Su nombre proviene de las llamadas trap houses, lugares relacionados con la fabricación y venta de
        drogas. Con el tiempo, el trap dejó de representar solamente una temática callejera y pasó a
        identificarse también por un sonido propio: ritmos minimalistas, bajos profundos, bombos 808 y
        patrones rápidos de hi-hats.
    </p>

    <!-- Orígenes -->
    <div class="row align-items-center mb-5">
        <div class="col-md-6">
            <img src="img/atlanta.jpg" alt="Orígenes del trap en Atlanta" class="img-fluid rounded shadow">
        </div>
        <div class="col-md-6">
            <h3>Orígenes</h3>
            <p>
                El trap comenzó a desarrollarse en Atlanta durante la década de 1990, después del auge
                del gangsta rap de las costas Este y Oeste. La palabra trap era utilizada en los barrios
                de Atlanta para referirse tanto a lugares vinculados con la venta de drogas como a una
                situación de la que era difícil escapar.
            </p>
            <p>
                El periodista musical Maurice Garland recuerda haber comenzado a escuchar el término
                alrededor de 1996 o 1997. Antes de que existiera el género como tal, grupos de Atlanta
                como Goodie Mob y OutKast ya utilizaban las palabras trap y trapping en sus canciones.
            </p>
            <p>
                El contexto social también fue fundamental: la epidemia del crack, la segregación, el
                encarcelamiento, la falta de educación y las pocas oportunidades económicas dieron origen
                a esta música como una forma de relatar esas experiencias y transformarlas en expresión
                artística.
            </p>
            <p><strong>Primeros referentes:</strong> Goodie Mob, OutKast, Cool Breeze, Ghetto Mafia y Dungeon Family.</p>
        </div>
    </div>

