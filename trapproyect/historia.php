                <h3 class="text-warning">¿Qué significa "Trap"?</h3>
                <p class="mb-0">
                    La palabra trap proviene de las trap houses, término utilizado en Atlanta para
                    identificar lugares relacionados con la venta y producción de drogas. Con el tiempo,
                    la palabra también adquirió un significado metafórico: representar una vida marcada
                    por circunstancias sociales y económicas de las que resulta difícil escapar.
                </p>
            </div>
        </div>
    </div>

    <!-- Expansión (imagen a la derecha) -->
    <div class="row align-items-center mb-5">
